from pyeqn import EqnTranslator
import sys
from functools import wraps


def trace_rule(rule):
    @wraps(rule)
    def wrapper(*p):
        print(rule.__name__ + ' >> ', p)
        result = rule(*p)
        print(rule.__name__ + ' << ', result)
        return result
    return wrapper


# @trace_rule
def eqn_text(t):
    return t


# @trace_rule
def eqn_bracketed(*args):
    return ' '.join(args)


# @trace_rule
def eqn_sup(*args):
    return args[0] + '^{' + args[1] + '}'


# @trace_rule
def eqn_sub(*args):
    return args[0] + '_{' + args[1] + '}'


# @trace_rule
def eqn_over(*args):
    return r'\frac{' + args[0] + '}{' + args[1] + '}'


# @trace_rule
def eqn_special_char(char):
    if char == char.upper():
        return '\\' + char[0].upper() + char[1:]
    return '\\' + char


# @trace_rule
def eqn_from(*args):
    return args[0] + '_{' + args[1] + '}'


# @trace_rule
def eqn_to(*args):
    return args[0] + '^{' + args[1] + '}'


# @trace_rule
def eqn_sum(*args):
    return '\\sum'


# @trace_rule
def eqn_sqrt(*args):
    return '\\sqrt{' + ' '.join(args) + '}'


symbols_map = {
    '>=' : '\\geq',
    '<=' : '\\leq',
    '<<' : '\\ll',
    '>>' : '\\gg',
    'inter' : '\\cap',
    'union' : '\\cup',
    '->' : '\\to',
    'grad' : '\\nabla',
    '!=' : '\\ne',
    '==' : '\\equiv',
    }


# @trace_rule
def eqn_mathop(*args):
    return symbols_map.get(args[0], '\\' + ''.join(*args))


# @trace_rule
def eqn_brackets(*args):
    return '\\left' + args[0] + args[1:-1] + '\\right' + args[-1] \
        if len(args) > 2 else '\\left' + args[0] + args[1:-1]


class HTMLDoc(object):
    def __init__(self):
        self.id = 0
        self._header = '''<!DOCTYPE html>
<meta charset="UTF-8">
<head>
    <title>LaTeX generated by eqn2mathjax</title>
    <link rel="stylesheet" type="text/css" 
    href="test/KaTeX/build/katex.min.css">

    <script type="text/javascript" 
    src="test/KaTeX/build/katex.min.js"></script>
</head>
<body>
'''
        self._footer = '''
</body>
</html>
'''
        self._mj = EqnTranslator.custom(sys.modules[__name__], 'eqn_')
        self._doc = self._header

    def write(self, filename):
        with open(filename, 'w') as f:
            self.flush(f)

    def flush(self, output=None):
        f = output if output else sys.stdout
        f.write(self._doc + self._footer)
        self._doc = self._header

    def add_equation(self, equation):
        self._doc += '''<p><span id="eqn{0}"></span></p>
        <script>
        katex.render("{1}", eqn{0});
        </script>
        '''.format(self.id, self._mj.translate(equation))
        self.id += 1


if __name__ == "__main__":
    import unittest as ut

    class EqnTests(ut.TestCase):
        def setUp(self):
            self.translator = EqnTranslator.custom(sys.modules[__name__],
                                                   'eqn_')
        def _runtests(self, examples):
            for case, expected in examples:
                result = self.translator.translate(case)
                self.assertEqual(result, expected)

        def test_scripts(self):
            cases = [('x sup 2', r'x^{2}'),
                     ('sum from n=1 to N x sub i', r'\sum_{n=1}^{N}x_{i}'),
                     ('x over 2', r'\frac{x}{2}'),
                     ('{ a sup 2 } over { x+1 }', r'\frac{a^{2}}{x+1}'),
                     ('{ a sup { x+y } } over { x+1 }',
                         r'\frac{a^{x+y}}{x+1}'),
                     ('omega over lambda', r'\frac{\omega}{\lambda}'),
                     ('pi sub { sqrt 2 }', r'\pi_{\sqrt{2}}'),
                     ('x sup 2 sub 3', 'x^{2}_{3}'),
                     ('prod from i=0 to N sum from k=0 to K x sub k sup i',
                      r'\prod_{i=0}^{N}\sum_{k=0}^{K}x_{k}^{i}')]
            self._runtests(cases)

    ut.main()
